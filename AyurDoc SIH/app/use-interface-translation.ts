function translateValue(value: string, language: InterfaceLanguage) {
  const whitespaceStart = value.match(/^\s*/)?.[0] ?? "";
  const whitespaceEnd = value.match(/\s*$/)?.[0] ?? "";
  const core = value.trim();
  if (!core) return value;
  const english = REVERSE.get(core);
  if (english) {
    const translated =
      language === "English" ? english : UI_TEXT[english][language];
    return `${whitespaceStart}${translated}${whitespaceEnd}`;
  }
  for (const dynamic of DYNAMIC_TEXT) {
    for (const pattern of dynamic.patterns) {
      const match = core.match(pattern);
      if (match)
        return `${whitespaceStart}${dynamic.render(language, match)}${whitespaceEnd}`;
    }
  }
  return value;
}

export function useInterfaceTranslation(language: InterfaceLanguage) {
  useEffect(() => {
    let frame = 0;
    const root = document.body;
    const observer = new MutationObserver(() => {
      window.cancelAnimationFrame(frame);
      frame = window.requestAnimationFrame(translatePage);
    });

    function translatePage() {
      observer.disconnect();
      document.documentElement.lang =
        { English: "en", हिन्दी: "hi", தமிழ்: "ta" }[language];
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      let node = walker.nextNode();
      while (node) {
        const parent = node.parentElement;
        if (
          parent &&
          !parent.closest("script, style, [data-no-translate], input, textarea")
        ) {
          const next = translateValue(node.nodeValue ?? "", language);
          if (next !== node.nodeValue) node.nodeValue = next;
        }
        node = walker.nextNode();
      }
      document
        .querySelectorAll<HTMLElement>("[placeholder], [title], [aria-label]")
        .forEach((element) => {
          for (const attribute of ["placeholder", "title", "aria-label"]) {
            const value = element.getAttribute(attribute);
            if (!value) continue;
            const next = translateValue(value, language).trim();
            if (next !== value) element.setAttribute(attribute, next);
          }
        });
      observer.observe(root, {
        subtree: true,
        childList: true,
        characterData: true,
        attributes: true,
        attributeFilter: ["placeholder", "title", "aria-label"],
      });
    }

    translatePage();
    return () => {
      observer.disconnect();
      window.cancelAnimationFrame(frame);
    };
  }, [language]);
}
